test("the M2 spike is not shipped", () => {
  // Plan v7's M2 gate calls the generated-placeholder spike "throwaway, non-shipping". `files` is an
  // allowlist, so this holds structurally — but the point of the spike is that it is disposable, and
  // an allowlist is one careless addition away from shipping it.
  assert.ok(existsSync(new URL("../spike/generated-placeholders/spike.mjs", import.meta.url)),
    "the spike should exist; M2 requires it");
  for (const entry of pkg.files) {
    assert.ok(!entry.startsWith("spike"),
      `package.json files includes '${entry}': the M2 spike must never be packed`);
  }

  // AND THE SPELLING CHECK ABOVE IS NOT THE CLAIM. `spike/generated-placeholders/README.md` says
  // "nothing here is packed"; this loop reads the ALLOWLIST, and `"./spike/"` does not start with
  // `spike`, nor does `"**/*.mjs"`. Either ships the spike and passes every assertion above — the
  // document's claim was stronger than its own named gate. So the artifact is packed and read.
    // `--ignore-scripts`, and it is a RACE FIX rather than a preference. `prepack` now runs
    // `npm run types`, so a bare `npm pack` regenerates `types/` — and `node --test` runs files
    // concurrently, so two packing tests plus every test that READS `types/` can meet a
    // half-written directory. Observed once as a single intermittent red in a full run that
    // passed three times after. These two call sites want the FILE LIST, which needs no
    // regeneration; the two tools that want a real tarball (`bundle-sizes`, `readme-newcomer`)
    // run as their own `verify` steps and MUST keep the hook.
  const listed = execFileSync("npm", ["pack", "--dry-run", "--json", "--ignore-scripts"],
    { cwd: new URL("../", import.meta.url).pathname, encoding: "utf8" });
  const files = JSON.parse(listed)[0].files.map((/** @type {{ path: string }} */ f) => f.path);
  assert.ok(files.length > 50, `npm pack listed ${files.length} file(s); the derivation is broken`);
  assert.deepEqual(files.filter((/** @type {string} */ f) => f.split("/")[0] === "spike"), [],
    "the M2 spike reached the packed artifact");
});

/**
 * THE README STATES `files` VERBATIM, AND NOTHING COMPARED THE TWO UNTIL IT WENT STALE.
 *
 * `### Loading from a browser without a bundler` tells a reader what the published package contains
 * by quoting the array: "`package.json`'s `files` is `["src/", "types/", "LICENSE", "NOTICE",
 * "README.md"]`". M-R S5 added `THIRD-PARTY-NOTICES.md` and that sentence was wrong the moment the
 * entry landed — found by grep while making the change, by no gate afterwards.
 *
 * `check:readme` cannot see it: the claim is prose, and M-D S12 recorded the rule it breaks — a
 * claim that CAN be executed and is left in prose is a claim nothing checks. It is executable here
 * because both sides are machine-readable, so the comparison is the repair rather than a cleverer
 * checker.
 */
test("the `files` array the README quotes is the one package.json declares", async () => {
  const manifest = JSON.parse(await readFile(new URL("package.json", root), "utf8"));
  const readme = await readFile(new URL("README.md", root), "utf8");

  const quoted = /`package\.json`'s `files` is `(\[[^`]*\])`/s.exec(readme);
  assert.ok(quoted, "the README no longer quotes `files`; delete this test or restore the sentence");

  // Parsed, not string-compared: the README wraps the array across lines and a whitespace difference
  // is not a claim about the package.
  const stated = JSON.parse(quoted[1].replace(/\s+/g, " "));
  assert.ok(Array.isArray(stated) && stated.length >= 4,
    `the README quotes ${JSON.stringify(stated)}, which is not a plausible file list`);
  assert.deepEqual(stated, manifest.files,
    "the README's `files` list is not what package.json ships");
});
