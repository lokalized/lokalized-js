test("every documented subpath resolves and imports", async () => {
  for (const subpath of DOCUMENTED_SUBPATHS) {
    const target = pkg.exports[subpath].import;
    assert.ok(target, `${subpath} declares no import target`);
    await assert.doesNotReject(
      () => import(new URL(target, root).href),
      `${subpath} -> ${target} failed to import`,
    );
  }
});

test("every subpath declares types before import", () => {
  // Condition order is significant: "types" must precede "import" or
  // TypeScript's node16/nodenext resolution picks the JS file first.
  for (const subpath of DOCUMENTED_SUBPATHS) {
    const conditions = Object.keys(pkg.exports[subpath]);
    assert.deepEqual(conditions, ["types", "import"], `${subpath} condition order`);
  }
});

test("every published directory is either in git or regenerated before packing", () => {
  // **PUBLISHING FROM A FRESH CLONE WOULD HAVE SHIPPED ZERO TYPESCRIPT DECLARATIONS.** `types/` is
  // in `package.json#files`, is in `.gitignore`, and is tracked by git not at all — it exists on
  // this machine only because somebody ran `npm run types` at some point. Reproduced rather than
  // reasoned about: `git archive HEAD` into a clean directory and `npm pack --dry-run` there packed
  // **0** `types/` entries against 54 from the working tree. Every TypeScript consumer of the first
  // publish from a clean checkout would have got a package with no types at all.
  //
  // The repair is a `prepack` hook, which npm runs for both `npm pack` and `npm publish`. THE RULE
  // BELOW IS THE INVARIANT RATHER THAN THE REPAIR: a published path that git does not carry must be
  // produced by a pre-pack script. That catches the next generated directory somebody adds to
  // `files`, which is the shape this was — nobody chose to ship an empty `types/`, it just followed
  // from two independently reasonable decisions.
  const tracked = (/** @type {string} */ entry) => {
    const listed = execFileSync("git", ["ls-files", "--", entry], { cwd: root, encoding: "utf8" });
    return listed.trim().length > 0;
  };

  const generated = pkg.files.filter((/** @type {string} */ entry) => !tracked(entry));
  assert.ok(generated.length > 0,
    "no published path is generated — if that is now true, this rule is vacuous and should be deleted");
  assert.ok(generated.includes("types/"),
    "the derivation broke: `types/` is generated and must be the case this rule is about");

  for (const entry of generated)
    assert.ok(typeof pkg.scripts?.prepack === "string" && pkg.scripts.prepack.length > 0,
      `'${entry}' is published but not in git, so a fresh clone would publish it EMPTY. ` +
      "It must be regenerated by a `prepack` script, which npm runs for both pack and publish");

  // AND THE HOOK MUST ACTUALLY PRODUCE THEM. A `prepack` running the wrong script satisfies the
  // assertion above and ships the same empty directory.
  assert.match(pkg.scripts.prepack, /\btypes\b/,
    "`prepack` must regenerate the declarations, not merely exist");
});

