/**
 * Production data encoder: pinned CLDR JSON -> runtime JavaScript modules.
 *
 * Reads the SHA-pinned artifacts vendored in the sibling lokalized-spec checkout and emits
 * `src/data/*.js`. This tool carries no CLDR knowledge: every semantic decision was made upstream
 * by CldrDataGenerator, and every encoding decision is recorded in the planning directory's ENCODING-DECISION.md.
 *
 * Guarantees, all verified by `--check`:
 *   - LOSSLESS: each emitted module is imported, decoded, and its canonical JCS projection compared
 *     byte-for-byte against the same projection of the source. Not a shape check — exact bytes.
 *   - Likely subtags additionally preserve every key, the full language-script-region triple, the
 *     presence bit, and absent/unknown behavior. Row absence and a present Latn row stay distinct.
 *   - REPRODUCIBLE: regeneration is byte-identical.
 *
 *   node tools/gen-data.js --write    emit modules
 *   node tools/gen-data.js --check    verify emitted modules are current, lossless and reproducible
 *   node tools/gen-data.js --measure  integrated size table (raw/min-ish/gzip-9/br-q11/br-q5)
 */
