/** Canonical JSON: sorted object keys, no whitespace. Matches the upstream generator exactly. */
const jcs = (value) => {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(jcs).join(",")}]`;
  return `{${Object.keys(value).sort().map((k) => `${JSON.stringify(k)}:${jcs(value[k])}`).join(",")}}`;
};

const js = (v) => JSON.stringify(v);
/**
 * THE ATTRIBUTION IS A LEGAL COMMENT, NOT A `//` LINE, AND THE DIFFERENCE IS WHAT A BUNDLER KEEPS.
 *
 * Until this change every generated module said "Contains data derived from Unicode CLDR … See
 * NOTICE" on a `//` line, which every minifier strips. Measured against the shipped esbuild: a
 * minified bundle of `src/index.js` was 322,205 bytes, carried the CLDR data, and the word
 * `copyright` occurred ZERO times in it. A `/*!` comment is the form bundlers preserve by
 * convention — esbuild, Terser and Rollup all honour it — so the notice now travels into whatever a
 * consumer builds.
 *
 * **IT IS BYTE-IDENTICAL IN EVERY MODULE ON PURPOSE.** esbuild DEDUPLICATES identical legal
 * comments — measured: three modules carrying the same banner produce one copy in the output — so
 * the attribution costs one copy in a bundle however many generated modules it pulls in. Any
 * per-file detail would defeat that, which is why the file-specific line below is a plain comment
 * and the notice above it carries nothing but the notice.
 */
